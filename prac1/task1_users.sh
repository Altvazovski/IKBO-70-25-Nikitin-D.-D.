#!/bin/bash
# Задача 1: вывести отсортированный в алфавитном порядке список
# имён пользователей из файла /etc/passwd.
#
# Формат строки /etc/passwd: username:x:UID:GID:comment:home:shell
# Нам нужно только первое поле (до первого ':').
#
# Использование: ./task1_users.sh [файл]
# Если файл не указан, по умолчанию используется /etc/passwd.

FILE="${1:-/etc/passwd}"

if [ ! -r "$FILE" ]; then
    echo "Ошибка: файл '$FILE' не найден или недоступен для чтения" >&2
    exit 1
fi

# grep -oE '^[^:]+'  -- вывести только совпавшую часть (-o), извлекая
# всё от начала строки (^) до первого символа ':' (класс [^:]+).
# sort -- сортировка результата по алфавиту.
grep -oE '^[^:]+' "$FILE" | sort
