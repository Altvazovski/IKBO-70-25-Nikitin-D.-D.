#!/bin/bash
# Задача 2: вывести 5 записей с наибольшими номерами портов (протоколов)
# из /etc/protocols в формате "номер имя", отсортированных по убыванию.
#
# Формат строки /etc/protocols: имя  номер  алиас  # комментарий
# Строки-комментарии начинаются с '#', также бывают пустые строки.
#
# Использование: ./task2_protocols.sh [файл] [N]
# N - сколько строк вывести (по умолчанию 5).

FILE="${1:-/etc/protocols}"
N="${2:-5}"

if [ ! -r "$FILE" ]; then
    echo "Ошибка: файл '$FILE' не найден или недоступен для чтения" >&2
    exit 1
fi

# grep -vE '^#|^$'      -- убираем строки-комментарии и пустые строки
# awk '{print $2, $1}'  -- меняем местами номер (2-е поле) и имя (1-е поле)
# sort -rn              -- числовая сортировка по убыванию (-n числовая, -r обратная)
# head -n "$N"          -- первые N строк результата
grep -vE '^#|^$' "$FILE" | awk '{print $2, $1}' | sort -rn | head -n "$N"
