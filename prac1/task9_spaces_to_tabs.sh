#!/bin/bash
# Задача 9: заменить в файле все последовательности из 4 пробелов
# на символ табуляции. Входной и выходной файлы задаются аргументами.
#
# Использование: ./task9_spaces_to_tabs.sh <входной_файл> <выходной_файл>

if [ $# -ne 2 ]; then
    echo "Использование: $0 <входной_файл> <выходной_файл>" >&2
    exit 1
fi

INPUT="$1"
OUTPUT="$2"

if [ ! -r "$INPUT" ]; then
    echo "Ошибка: файл '$INPUT' не найден или недоступен для чтения" >&2
    exit 1
fi

# sed 's/    /\t/g'  -- заменить каждую последовательность ровно из
# 4 пробелов на символ табуляции ('\t') по всей строке (флаг g).
# Так как группы по 4 пробела не пересекаются, одного прохода с /g
# достаточно даже для 8, 12 и т.д. пробелов подряд.
sed 's/    /\t/g' "$INPUT" > "$OUTPUT"

echo "Готово: результат записан в '$OUTPUT'"
