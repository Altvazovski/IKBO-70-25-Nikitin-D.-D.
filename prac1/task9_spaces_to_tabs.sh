#!/bin/bash
# Задача 9: заменить в файле все последовательности из 4 пробелов

if [ $# -ne 2 ]; then
    echo "Использование: $0 <входной_файл> <выходной_файл>" >&2
    exit 1
fi

INPUT="$1"
OUTPUT="$2"

if [ ! -r "$INPUT" ]; then
    echo "Ошибка: файл '$INPUT' не найден или недоступен для чтения" >&2
    exit 1
fi

sed 's/    /\t/g' "$INPUT" > "$OUTPUT"

echo "Готово: результат записан в '$OUTPUT'"
