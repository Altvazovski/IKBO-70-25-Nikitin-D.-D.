#!/bin/bash
# Задача 4: вывести все уникальные идентификаторы (по правилам
# C/C++/Java: начинается с буквы или '_', далее буквы/цифры/'_')
# из указанного файла, без повторений, отсортированные по алфавиту,
# в одну строку через пробел.
#
# Использование: ./task4_identifiers.sh файл.c

if [ $# -ne 1 ]; then
    echo "Использование: $0 <файл>" >&2
    exit 1
fi

FILE="$1"

if [ ! -r "$FILE" ]; then
    echo "Ошибка: файл '$FILE' не найден или недоступен для чтения" >&2
    exit 1
fi

# grep -oE '[A-Za-z_][A-Za-z0-9_]*'  -- извлечь все подстроки, подходящие
#   под правило идентификатора (первый символ - буква/подчёркивание,
#   остальные - буквы/цифры/подчёркивание). Ключевые слова языка (int,
#   return и т.д.) тоже подходят под это правило и в задаче трактуются
#   как обычные идентификаторы (см. пример вывода: "int", "return" есть
#   в результате).
# sort -u                            -- отсортировать и убрать дубликаты.
# tr '\n' ' '                        -- склеить строки в одну через пробел.
# sed 's/ $/\n/'                     -- убрать лишний пробел в конце и
#   добавить перевод строки после последнего слова.
grep -oE '[A-Za-z_][A-Za-z0-9_]*' "$FILE" | sort -u | tr '\n' ' ' | sed 's/ $/\n/'
